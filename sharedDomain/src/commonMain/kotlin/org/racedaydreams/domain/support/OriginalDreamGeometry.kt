private fun schematicRoute(id: String, name: String, vararg p: Double): DreamRoutes.Route {
    val vertices = mutableListOf<DreamRoutes.Vertex>()
    for (i in p.indices step 2) vertices.add(DreamRoutes.Vertex(p[i], p[i + 1]))
    return DreamRoutes.Route(id, name, coachingReadOnlyList(vertices))
}

internal fun dreamProvenance(routeId: String): String =
    when (routeId) {
        "paris-2026-geo-v1" ->
            "Annual Marathon de Paris2026: approximate OSM street-itinerary reconstruction, © OpenStreetMap contributors, via Geofabrik; ODbL-1.0 data. Factual course: police order2026-00388 and ASO2026 guide. Not certified geometry or navigation. The42195m equivalent axis is separate from the approximate43.22km street line."
        "paris-2024-olympic-geo-v1" ->
            "Paris2024 Olympic marathon community geometry by Thomas Krakow (Running-tomy), via Wikimedia Commons, ODbL-1.0. This is not the annual Paris Marathon, official/certified geometry or navigation. The marathon-equivalent axis is separate from the source line."
        "new-york-2026-geo-v1" ->
            "Approximate New York2026 road centreline, © OpenStreetMap contributors, prepared by MARATHON TRIP; ODbL-1.0 data. Not official/certified geometry or navigation. The marathon-equivalent axis is separate from the approximate42.67 km retained line."
        "london-historical-geo-v1" ->
            "Approximate historical London course line published2023 by Georgios Karamanis under MIT. Course edition and survey accuracy unspecified. Not an official current course or navigation. The marathon-equivalent axis is separate from the approximate42.78 km source line."
        "tokyo-2026-geo-v1" ->
            "Approximate Tokyo2026 participant GPS trace, simplified from CC0 data published by kekomat/marathon-gpx-dataset. Not an official race map or navigation. The marathon-equivalent axis is separate from the observed42.75 km trace."
        "berlin-2014-geo-v1" ->
            "Approximate Berlin2014 participant GPS trace, simplified from an MIT-licensed source by Alexandre Donciu-Julin. Not a current official course or navigation. The marathon-equivalent axis is separate from the observed43.01 km trace."
        else ->
            "Original v2 course-inspired schematic; geographic replacement is still in progress. Not official course artwork or navigation."
    }

