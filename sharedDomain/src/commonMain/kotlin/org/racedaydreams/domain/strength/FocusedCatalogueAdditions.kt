    class Entry(
        id: String,
        name: String,
        aliases: List<String>,
        category: String,
        region: Region,
        profile: MeasurementProfile,
        role: Role,
        primary: Set<ExerciseMetadata.BodyArea>,
        secondary: Set<ExerciseMetadata.BodyArea>,
        kit: Set<Equipment>,
        pattern: String,
        setup: String,
        movement: String,
        cue: String,
        mistake: String,
        alternatives: List<String>,
        asset: String,
        phases: List<String>,
        equipmentLabel: String = if (kit.isEmpty()) "bodyweight" else "resistance bands",
        suitability: Suitability = Suitability.BEGINNER_FRIENDLY,
    ) {
        val definition =
            ExerciseCatalog.Definition(
                StrengthExercise(
                    id,
                    name,
                    region,
                    StrengthExercise.Mode.BODYWEIGHT,
                    false,
                    profile,
                ),
                category,
                equipmentLabel,
                Immutable.copyList(aliases),
            )
        val metadata =
            ExerciseMetadata(
                id,
                role,
                setOf(role),
                primary,
                secondary,
                suitability,
                EquipmentRequirement(listOf(kit)),
            )
        val guide =
            TechniqueGuide(
                pattern,
                setup,
                movement,
                listOf(cue),
                listOf(mistake),
                (primary + secondary).joinToString { it.label() },
                alternatives,
            )
        val artwork = TechniqueIllustrations.Artwork(asset, "$name. $setup $movement", phases)
    }

