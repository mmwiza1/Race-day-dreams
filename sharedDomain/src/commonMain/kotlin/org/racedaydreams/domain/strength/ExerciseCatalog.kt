package org.racedaydreams.domain.strength

import kotlin.jvm.JvmStatic
import org.racedaydreams.domain.coaching.Immutable

/** Original catalogue. Stable identities and definitions remain unchanged across platforms. */
object ExerciseCatalog {
    data class Definition(
        private val exercise: StrengthExercise,
        private val category: String,
        private val equipment: String,
        private val aliases: List<String>,
    ) {
        fun exercise(): StrengthExercise = exercise

        fun category(): String = category

        fun equipment(): String = equipment

        fun aliases(): List<String> = aliases

        override fun toString(): String =
            "Definition[exercise=$exercise, category=$category, equipment=$equipment, aliases=$aliases]"
    }

    private val definitions = build()

    @JvmStatic fun definitions(): List<Definition> = definitions

    @JvmStatic
    fun exercises(): List<StrengthExercise> = Immutable.copyList(definitions.map { it.exercise() })

    @JvmStatic
    fun definition(id: String?): Definition? = definitions.firstOrNull { it.exercise().id() == id }

    private fun add(
        out: MutableList<Definition>,
        id: String,
        name: String,
        category: String,
        equipment: String,
        region: StrengthExercise.Region,
        mode: StrengthExercise.Mode,
        profile: StrengthExercise.MeasurementProfile,
        estimate: Boolean,
        aliases: List<String>,
    ) {
        out.add(
            Definition(
                StrengthExercise(id, name, region, mode, estimate, profile),
                category,
                equipment,
                Immutable.copyList(aliases),
            )
        )
    }

