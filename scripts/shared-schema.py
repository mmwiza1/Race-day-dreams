#!/usr/bin/env python3
"""Generate shared SQLite DDL from the exact existing Android migration literals."""
import importlib.util
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('schema_tests', ROOT / 'scripts/test-schema.py')
schema = importlib.util.module_from_spec(spec)
spec.loader.exec_module(schema)
target = ROOT / 'sharedStorage/src/commonMain/kotlin/org/racedaydreams/storage/SchemaStatements.kt'
lines = ['package org.racedaydreams.storage', '', '// Generated by scripts/shared-schema.py; edit ProfileDatabase migration markers instead.', 'internal object SchemaStatements {', '    val versions: List<List<String>> = listOf(']
for version in range(1, 20):
    lines.append('        listOf(')
    for statement in schema.schema_statements(version):
        literal = json.dumps(statement, ensure_ascii=False).replace('$', '\\$')
        lines.append(f'            {literal},')
    lines.append('        ),')
lines.extend(['    )', '}', ''])
content = '\n'.join(lines)
# Kotlin formatter can wrap declarations without changing their string literals.
if '--check' in sys.argv:
    import ast
    import re
    # Compare migration boundaries as well as flattened statements: moving DDL into
    # an earlier/later version would otherwise hide an incompatible upgrade.
    stack = []
    actual = None
    source = target.read_text().partition('val versions')[2]
    for token in re.findall(r'listOf\s*\(|"(?:\\.|[^"\\])*"|\)', source):
        if token.startswith('listOf'):
            stack.append([])
        elif token == ')':
            completed = stack.pop()
            if stack:
                stack[-1].append(completed)
            else:
                actual = completed
        else:
            stack[-1].append(ast.literal_eval(token.replace('\\$', '$')))
    expected = [schema.schema_statements(v) for v in range(1, 20)]
    if stack or actual != expected:
        raise SystemExit('Shared schema differs from Android; run scripts/shared-schema.py')
    print('Shared schema: all 19 migration boundaries/statements match Android exactly')
else:
    target.write_text(content)
