package org.racedaydreams.coach.application

import androidx.compose.material3.Text
import androidx.compose.runtime.*
import androidx.compose.runtime.saveable.rememberSaveable
import org.racedaydreams.coach.CoachButton
import org.racedaydreams.coach.CoachPage
import org.racedaydreams.coach.strength.*
import org.racedaydreams.domain.time.CalendarDates
import org.racedaydreams.domain.time.DayOfWeek
import org.racedaydreams.domain.time.LocalDate
import platform.Foundation.NSUUID

private enum class ProgrammePage {
    BUILDER,
    TEMPLATES,
    CUSTOM,
}

@Composable
internal fun AppleStrengthProgrammes(
    session: AppleCoachSession<*>,
    reviewDraftId: String? = null,
    onBack: () -> Unit,
) {
    val author = session.authoring
    val generator = session.generation
    val authored by author.state.collectAsState()
    val generated by generator.state.collectAsState()
    var page by
        rememberSaveable(reviewDraftId) {
            mutableStateOf(
                if (reviewDraftId == null) ProgrammePage.BUILDER else ProgrammePage.TEMPLATES
            )
        }
    val presentation = remember { appleProgrammePresentation() }
    val activated = {
        session.services.operations.refresh()
        session.gym.refresh()
        onBack()
    }
    LaunchedEffect(page, reviewDraftId) {
        when {
            page != ProgrammePage.TEMPLATES -> author.reload()
            reviewDraftId != null -> generator.open(reviewDraftId) {}
            else -> generator.reload()
        }
    }
    if (reviewDraftId != null && generated.draft?.id() != reviewDraftId) {
        CoachPage {
            CoachButton("Back", onBack)
            Text(
                if (generated.busy) "Loading saved preview…"
                else generated.error ?: "Loading saved preview…"
            )
        }
        return
    }
    when (page) {
        ProgrammePage.BUILDER ->
            SharedStrengthProgrammeBuilderScreen(
                author,
                authored,
                presentation,
                {},
                onBack = onBack,
                onActivated = activated,
                onCreateCustom = { page = ProgrammePage.CUSTOM },
                onTemplates = { page = ProgrammePage.TEMPLATES },
            )
        ProgrammePage.TEMPLATES ->
            SharedStrengthGenerationScreen(
                generator,
                generated,
                presentation,
                AppleCalendarDates::today,
                { NSUUID().UUIDString },
                {},
                onBack = { if (reviewDraftId == null) page = ProgrammePage.BUILDER else onBack() },
                onActivated = activated,
            )
        ProgrammePage.CUSTOM ->
            SharedCustomStrengthExerciseScreen(
                author,
                authored,
                onBack = { page = ProgrammePage.BUILDER },
                onSaved = {
                    session.services.operations.refresh()
                    page = ProgrammePage.BUILDER
                },
            )
    }
}

private fun appleProgrammePresentation(): ProgrammeScreenPresentation =
    ProgrammeScreenPresentation(
        formatDate = AppleCalendarDates::label,
        formatInputDate = ::ukInputDate,
        parseInputDate = { value ->
            val fields = value.split('/')
            require(
                fields.size == 3 &&
                    fields[0].length == 2 &&
                    fields[1].length == 2 &&
                    fields[2].length == 4
            ) {
                "Enter the date as DD/MM/YYYY."
            }
            CalendarDates.of(fields[2].toInt(), fields[1].toInt(), fields[0].toInt())
        },
        weekday = { iso -> DayOfWeek.values().single { it.getValue() == iso } },
        weekdayLabel = { day, short ->
            val full = day.name.lowercase().replaceFirstChar { it.uppercase() }
            if (short) full.take(3) else full
        },
        formatExercise = { it.name() },
        formatTarget = ::appleGymTarget,
        formatNumber = { it.toString().removeSuffix(".0") },
    )

private fun ukInputDate(date: LocalDate): String =
    "${date.getDayOfMonth().toString().padStart(2, '0')}/" +
        "${date.getMonthValue().toString().padStart(2, '0')}/" +
        date.getYear().toString().padStart(4, '0')
