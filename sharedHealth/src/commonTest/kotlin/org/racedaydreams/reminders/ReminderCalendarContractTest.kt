    @Test
    fun regionalGapOverlapAndSkippedDayResolutionMatchesOriginalEvidence() {
        for (c in cases) {
            val actual =
                KotlinxReminderCalendar.resolve(CalendarDates.of(c.y, c.m, c.d), c.nano, c.zone)
            assertEquals(c.epoch, actual.instant.getEpochSecond(), c.toString())
            assertEquals(123456789, actual.instant.getNano(), c.toString())
            assertEquals(c.day, actual.date.toEpochDay(), c.toString())
            assertEquals(c.resolvedNano, actual.nanoOfDay, c.toString())
            assertEquals(actual, KotlinxReminderCalendar.at(actual.instant, c.zone))
        }
    }

    @Test
    fun datelineSkipDoesNotPretendAnAlarmIsOnTheMissingEvening() {
        val entry =
            ReminderPlanEntry(
                org.racedaydreams.domain.PlannedWorkout(
                    "r",
                    CalendarDates.of(2011, 12, 31),
                    org.racedaydreams.domain.WorkoutCategory.LONG_RUN,
                    5.0,
                    null,
                    emptyList(),
                    null,
                ),
                1,
                ReminderPlanEntry.Status.PLANNED,
            )
        val settings =
            ReminderSettings(
                ReminderSettings.Mode.ALL,
                19 * 3600 * 1000000000L,
                null,
                "Pacific/Apia",
            )
        val alarm = assertNotNull(ReminderRules.candidate(entry, settings, KotlinxReminderCalendar))
        assertFalse(
            ReminderRules.canDeliver(
                alarm,
                entry,
                settings,
                { alarm.triggerAt() },
                true,
                KotlinxReminderCalendar,
            )
        )
    }
